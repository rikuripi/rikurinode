class FetchJson(unittest.TestCase):
    """The real fetcher turns every transport failure into CannotAudit (verifier's nit 2, 2026-10-21)."""

    def failing(self, error):
        with mock.patch("urllib.request.urlopen", side_effect=error):
            with self.assertRaises(oa.CannotAudit) as caught:
                oa.fetch_json(oa.OSV + "/query", {"package": {"name": "x", "ecosystem": "crates.io"}})
        return str(caught.exception)

    def test_http_error_url_error_and_incomplete_read(self):
        self.assertIn("HTTP 503", self.failing(urllib.error.HTTPError(oa.OSV, 503, "down", {}, None)))
        self.assertIn("cannot reach", self.failing(urllib.error.URLError("no route")))
        self.assertIn("cannot reach", self.failing(http.client.IncompleteRead(b"")))
        self.assertIn("cannot reach", self.failing(OSError("socket closed")))

    def test_not_json(self):
        response = mock.MagicMock()
        response.__enter__.return_value.read.return_value = b"<html>"
        with mock.patch("urllib.request.urlopen", return_value=response):
            with self.assertRaises(oa.CannotAudit) as caught:
                oa.fetch_json(oa.OSV + "/vulns/X")
        self.assertIn("not JSON", str(caught.exception))


class Pins(unittest.TestCase):
    def test_one_query_per_action_and_every_pin_placed(self):
        workflow = ("jobs:\n  x:\n    steps:\n      - uses: %s # v7.0.1\n      - uses: actions/checkout@%s # v7.0.0\n"
                    % (CHECKOUT, "b" * 40))
        fake = Fake({"/query": {"vulns": [vuln("GHSA-mrrh-fwg8-r2c3", name="actions/checkout",
                                               events=[{"introduced": "0"}, {"fixed": "7.0.1"}])]}})
        rc, out, _ = run(fake, workflow=workflow)
        self.assertEqual(rc, 1)
        self.assertEqual(len([url for url, _ in fake.calls if url.endswith("/query")]), 1)
        self.assertIn("FINDING: action actions/checkout 7.0.0: GHSA-mrrh-fwg8-r2c3", out)
        self.assertNotIn("actions/checkout 7.0.1: GHSA", out)
        self.assertIn("1 actions (2 pins): 1 findings", out)


class Chunking(unittest.TestCase):
    def test_more_than_a_thousand_crates_go_in_two_calls(self):
        blocks = "".join('\n[[package]]\nname = "crate%d"\nversion = "1.0.0"\nsource = "registry+x"\n' % i for i in range(1001))
        fake = Fake()
        rc, out, _ = run(fake, lock="version = 4\n" + blocks)
        self.assertEqual(rc, 0)
        batches = [len(body["queries"]) for url, body in fake.calls if url.endswith("/querybatch")]
        self.assertEqual(batches, [1000, 1])
        self.assertIn("1001 crates", out)


