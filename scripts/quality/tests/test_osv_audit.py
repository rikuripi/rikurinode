class Fake:
    """A fetcher: answers by URL suffix, or raises; records every call."""

    def __init__(self, answers=None, raises=None):
        self.answers = answers or {}
        self.raises = raises
        self.calls = []

    def __call__(self, url, body=None):
        self.calls.append((url, body))
        if self.raises is not None:
            raise self.raises
        for suffix, answer in self.answers.items():
            if url.endswith(suffix):
                return answer(body) if callable(answer) else answer
        if url.endswith("/querybatch"):
            return {"results": [{} for _ in body["queries"]]}
        if url.endswith("/query"):
            return {}
        return {"id": url.rsplit("/", 1)[1], "aliases": [], "summary": ""}


def make_repo(folder, lock=LOCK, workflow=WORKFLOW, deny=DENY):
    os.makedirs(os.path.join(folder, "control-plane"))
    os.makedirs(os.path.join(folder, ".github", "workflows"))
    with open(os.path.join(folder, "control-plane", "Cargo.lock"), "w") as f:
        f.write(lock)
    with open(os.path.join(folder, "control-plane", "deny.toml"), "w") as f:
        f.write(deny)
    with open(os.path.join(folder, ".github", "workflows", "ci.yml"), "w") as f:
        f.write(workflow)
    return folder


def run(fake, **repo):
    """(rc, stdout, stderr) of main on a temporary repository with this fetcher."""
    with tempfile.TemporaryDirectory() as folder:
        make_repo(folder, **repo)
        out, err = io.StringIO(), io.StringIO()
        rc = oa.main([folder], fetch=fake, out=out, err=err)
    return rc, out.getvalue(), err.getvalue()


def vuln(vuln_id, name="tj-actions/changed-files", events=None, versions=None, ecosystem=oa.ACTIONS, rtype="ECOSYSTEM"):
    entry = {"package": {"ecosystem": ecosystem, "name": name}}
    if events is not None:
        entry["ranges"] = [{"type": rtype, "events": events}]
    if versions is not None:
        entry["versions"] = versions
    return {"id": vuln_id, "affected": [entry]}


class LockedCrates(unittest.TestCase):
    def test_workspace_crates_are_not_asked(self):
        registry, other = oa.locked_crates(LOCK)
        self.assertEqual(registry, [("tokio", "1.53.2")])
        self.assertEqual(other, [])

    def test_a_crate_from_another_source_is_named_not_asked(self):
        lock = LOCK + '\n[[package]]\nname = "security-core"\nversion = "0.3.0"\nsource = "git+https://github.com/x/y?rev=abc#abc"\n'
        registry, other = oa.locked_crates(lock)
        self.assertEqual(registry, [("tokio", "1.53.2")])
        self.assertEqual(other, [("security-core", "0.3.0", "git+https://github.com/x/y?rev=abc#abc")])
        fake = Fake()
        rc, out, _ = run(fake, lock=lock)
        self.assertEqual(rc, 0)
        self.assertIn("not on crates.io, not asked: security-core 0.3.0", out)
        self.assertIn("1 not asked", out)
        asked = [q["package"]["name"] for url, body in fake.calls if url.endswith("/querybatch") for q in body["queries"]]
        self.assertEqual(asked, ["tokio"])

    def test_a_block_without_a_version_cannot_be_audited(self):
        with self.assertRaises(oa.CannotAudit):
            oa.locked_crates('[[package]]\nname = "x"\nsource = "registry+y"\n')
        rc, _, err = run(Fake(), lock='[[package]]\nname = "x"\nsource = "registry+y"\n')
        self.assertEqual(rc, 2)
        self.assertIn("could not audit", err)


class PinnedActions(unittest.TestCase):
    def parse(self, text):
        with tempfile.TemporaryDirectory() as folder:
            path = os.path.join(folder, "w.yml")
            with open(path, "w") as f:
                f.write(text)
            return oa.pinned_actions([path])

    def test_a_pin_with_its_version_comment(self):
        found = self.parse(WORKFLOW)
        self.assertEqual([(name, version) for name, version, _ in found], [("actions/checkout", "7.0.1")])
        self.assertTrue(found[0][2].endswith("w.yml:5"))

    def test_a_subpath_and_a_comment_without_v(self):
        found = self.parse("      - uses: owner/repo/sub/path@%s # 2.1.0 (pinned)\n" % ("a" * 40))
        self.assertEqual([(n, v) for n, v, _ in found], [("owner/repo", "2.1.0")])

    def test_a_floating_tag_cannot_be_audited(self):
        with self.assertRaises(oa.CannotAudit) as caught:
            self.parse("      - uses: actions/checkout@v4 # v4\n")
        self.assertIn("not pinned to a 40-hex commit", str(caught.exception))
        rc, _, err = run(Fake(), workflow="jobs:\n  x:\n    steps:\n      - uses: actions/checkout@v4\n")
        self.assertEqual(rc, 2)
        self.assertIn("not pinned", err)

    def test_a_pin_without_a_version_comment_cannot_be_audited(self):
        with self.assertRaises(oa.CannotAudit) as caught:
            self.parse("      - uses: %s\n" % CHECKOUT)
        self.assertIn("names no version", str(caught.exception))
        with self.assertRaises(oa.CannotAudit):
            self.parse("      - uses: %s # pinned 2026\n" % CHECKOUT)
        rc, _, err = run(Fake(), workflow="jobs:\n  x:\n    steps:\n      - uses: %s\n" % CHECKOUT)
        self.assertEqual(rc, 2)

    def test_lines_that_are_not_uses_are_ignored(self):
        self.assertEqual(self.parse("name: x\n# uses: nothing\nrun: echo uses:\n"), [])


class Ranges(unittest.TestCase):
    def test_fixed_is_exclusive_and_introduced_inclusive(self):
        record = vuln("GHSA-mrrh-fwg8-r2c3", events=[{"introduced": "0"}, {"fixed": "46.0.1"}])
        self.assertTrue(oa.affects(record, "tj-actions/changed-files", "45.0.7"))
        self.assertTrue(oa.affects(record, "tj-actions/changed-files", "46.0.0"))
        self.assertFalse(oa.affects(record, "tj-actions/changed-files", "46.0.1"))
        self.assertFalse(oa.affects(record, "tj-actions/changed-files", "47"))
        record = vuln("X", events=[{"introduced": "2.1"}, {"fixed": "3"}])
        self.assertFalse(oa.affects(record, "tj-actions/changed-files", "2.0.9"))
        self.assertTrue(oa.affects(record, "tj-actions/changed-files", "2.1"))
        self.assertTrue(oa.affects(record, "tj-actions/changed-files", "v2.1.0"))
        self.assertTrue(oa.affects(record, "tj-actions/changed-files", "2.9.9"))
        self.assertFalse(oa.affects(record, "tj-actions/changed-files", "3"))
        self.assertFalse(oa.affects(record, "tj-actions/changed-files", "3.0.0"))

    def test_last_affected_is_inclusive_and_an_open_interval_runs_on(self):
        record = vuln("X", events=[{"introduced": "1"}, {"last_affected": "1.5"}])
        self.assertTrue(oa.affects(record, "tj-actions/changed-files", "1.5"))
        self.assertFalse(oa.affects(record, "tj-actions/changed-files", "1.5.1"))
        record = vuln("X", events=[{"introduced": "4"}])
        self.assertTrue(oa.affects(record, "tj-actions/changed-files", "900.0"))
        self.assertFalse(oa.affects(record, "tj-actions/changed-files", "3.9"))

    def test_an_explicit_version_list_and_the_name_case(self):
        record = vuln("X", versions=["1.2.3", "v1.2.4"])
        self.assertTrue(oa.affects(record, "TJ-Actions/Changed-Files", "1.2.4"))
        self.assertFalse(oa.affects(record, "tj-actions/changed-files", "1.2.5"))

    def test_another_package_or_ecosystem_does_not_count(self):
        self.assertFalse(oa.affects(vuln("X", name="other/action", events=[{"introduced": "0"}]), "tj-actions/changed-files", "1"))
        self.assertFalse(oa.affects(vuln("X", ecosystem="npm", events=[{"introduced": "0"}]), "tj-actions/changed-files", "1"))

    def test_a_git_only_range_cannot_be_evaluated(self):
        record = vuln("X", events=[{"introduced": "0"}], rtype="GIT")
        with self.assertRaises(oa.CannotAudit):
            oa.affects(record, "tj-actions/changed-files", "1")

    def test_an_unparsable_version_cannot_be_audited(self):
        with self.assertRaises(oa.CannotAudit):
            oa.version_tuple("latest")
        with self.assertRaises(oa.CannotAudit):
            oa.affects(vuln("X", events=[{"introduced": "0"}, {"fixed": "1.0-rc1"}]), "tj-actions/changed-files", "0.9")


class IgnoreList(unittest.TestCase):
    def test_string_and_table_forms_and_comments(self):
        deny = ('[advisories]\nyanked = "deny"\n# RUSTSEC-2000-0001 in a comment is not an entry\n'
                'ignore = [\n    "RUSTSEC-2026-0001", # reason here\n'
                '    { id = "GHSA-aaaa-bbbb-cccc", reason = "not reachable" },\n'
                '    "CVE-2026-12345",\n    "RUSTSEC-2026-0001",\n]\n\n[licenses]\nallow = ["RUSTSEC-2026-9999"]\n')
        self.assertEqual(oa.ignored_ids(deny), ["RUSTSEC-2026-0001", "GHSA-aaaa-bbbb-cccc", "CVE-2026-12345"])

    def test_empty_and_absent(self):
        self.assertEqual(oa.ignored_ids(DENY), [])
        self.assertEqual(oa.ignored_ids('[licenses]\nallow = ["MIT"]\n'), [])
        self.assertEqual(oa.ignored_ids("[advisories]\nyanked = \"deny\"\n"), [])

    def test_a_finding_is_ignored_by_alias_and_counted(self):
        fake = Fake({
            "/querybatch": {"results": [{"vulns": [{"id": "RUSTSEC-2026-0382", "modified": "x"}]}]},
            "/vulns/RUSTSEC-2026-0382": {"id": "RUSTSEC-2026-0382", "aliases": ["CVE-2026-111943", "GHSA-aaaa-bbbb-cccc"],
                                         "summary": "Certificate verification may accept distrusted intermediates"},
        })
        deny = '[advisories]\nignore = [\n    { id = "GHSA-aaaa-bbbb-cccc", reason = "not reachable" },\n]\n'
        rc, out, err = run(fake, deny=deny)
        self.assertEqual(rc, 0, err)
        self.assertIn("ignored by deny.toml (GHSA-aaaa-bbbb-cccc): crate tokio 1.53.2: RUSTSEC-2026-0382", out)
        self.assertIn("0 findings, 1 ignored", out)
        self.assertNotIn("FINDING:", out)
        self.assertNotIn("matched nothing", out)

    def test_an_entry_that_matched_nothing_is_printed(self):
        rc, out, _ = run(Fake(), deny='[advisories]\nignore = ["RUSTSEC-2020-0001"]\n')
        self.assertEqual(rc, 0)
        self.assertIn("ignore entry matched nothing: RUSTSEC-2020-0001", out)

    def test_an_unrelated_entry_does_not_suppress_a_finding(self):
        # Verifier's OA7 (2026-10-21): a match of every entry to every finding survived the tests.
        fake = Fake({
            "/querybatch": {"results": [{"vulns": [{"id": "RUSTSEC-2026-0382", "modified": "x"}]}]},
            "/vulns/RUSTSEC-2026-0382": {"id": "RUSTSEC-2026-0382", "aliases": ["CVE-2026-111943"], "summary": "Bad certs"},
        })
        rc, out, _ = run(fake, deny='[advisories]\nignore = ["RUSTSEC-2020-0001", { id = "GHSA-zzzz-zzzz-zzzz", reason = "other" }]\n')
        self.assertEqual(rc, 1)
        self.assertIn("FINDING: crate tokio 1.53.2: RUSTSEC-2026-0382 (CVE-2026-111943): Bad certs", out)
        self.assertIn("ignore entry matched nothing: RUSTSEC-2020-0001", out)
        self.assertIn("ignore entry matched nothing: GHSA-zzzz-zzzz-zzzz", out)
        self.assertNotIn("ignored by deny.toml", out)
        self.assertIn("1 findings, 0 ignored", out)


class ExitCodes(unittest.TestCase):
    def test_clean_is_0_with_the_counts(self):
        fake = Fake()
        rc, out, err = run(fake)
        self.assertEqual((rc, err), (0, ""))
        self.assertIn("asked OSV about 1 crates and 1 actions (1 pins): 0 findings, 0 ignored, 0 not asked -> clean", out)
        urls = [url for url, _ in fake.calls]
        self.assertEqual(urls, [oa.OSV + "/querybatch", oa.OSV + "/query"])
        self.assertEqual(fake.calls[0][1], {"queries": [{"package": {"name": "tokio", "ecosystem": "crates.io"}, "version": "1.53.2"}]})
        self.assertEqual(fake.calls[1][1], {"package": {"name": "actions/checkout", "ecosystem": "GitHub Actions"}})

    def test_a_crate_finding_is_1(self):
        fake = Fake({
            "/querybatch": {"results": [{"vulns": [{"id": "RUSTSEC-2026-0382", "modified": "x"}]}]},
            "/vulns/RUSTSEC-2026-0382": {"id": "RUSTSEC-2026-0382", "aliases": ["CVE-2026-111943"], "summary": "Bad certs"},
        })
        rc, out, _ = run(fake)
        self.assertEqual(rc, 1)
        self.assertIn("FINDING: crate tokio 1.53.2: RUSTSEC-2026-0382 (CVE-2026-111943): Bad certs", out)
        self.assertIn("1 findings, 0 ignored, 0 not asked -> FINDINGS", out)

    def test_an_action_finding_is_1_and_a_fixed_one_is_not(self):
        answers = {"/query": {"vulns": [vuln("GHSA-mrrh-fwg8-r2c3", name="actions/checkout",
                                             events=[{"introduced": "0"}, {"fixed": "7.0.1"}])]}}
        rc, out, _ = run(Fake(answers))
        self.assertEqual(rc, 0, out)
        answers = {"/query": {"vulns": [vuln("GHSA-mrrh-fwg8-r2c3", name="actions/checkout",
                                             events=[{"introduced": "0"}, {"fixed": "7.0.2"}])]}}
        rc, out, _ = run(Fake(answers))
        self.assertEqual(rc, 1)
        self.assertIn("FINDING: action actions/checkout 7.0.1: GHSA-mrrh-fwg8-r2c3", out)

    def test_an_http_error_is_2(self):
        rc, out, err = run(Fake(raises=oa.CannotAudit("HTTP 503 from https://api.osv.dev/v1/querybatch")))
        self.assertEqual(rc, 2)
        self.assertIn("could not audit: HTTP 503", err)
        self.assertNotIn("clean", out)

    def test_an_answer_that_is_not_json_is_2(self):
        rc, _, err = run(Fake(raises=oa.CannotAudit("not JSON from https://api.osv.dev/v1/querybatch")))
        self.assertEqual(rc, 2)
        self.assertIn("not JSON", err)

    def test_an_answer_of_the_wrong_shape_is_2(self):
        rc, _, err = run(Fake({"/querybatch": {"results": "yes"}}))
        self.assertEqual(rc, 2)
        self.assertIn("no results for 1 queries", err)
        rc, _, err = run(Fake({"/querybatch": {"results": [{}, {}]}}))
        self.assertEqual(rc, 2)
        self.assertIn("2 results for 1 queries", err)
        rc, _, err = run(Fake({"/querybatch": {"results": [{"vulns": [{"modified": "x"}]}]}}))
        self.assertEqual(rc, 2)
        self.assertIn("no id", err)
        rc, _, err = run(Fake({"/query": ["not", "an", "object"]}))
        self.assertEqual(rc, 2)
        rc, _, err = run(Fake({"/querybatch": {"results": [{"next_page_token": "more"}]}}))
        self.assertEqual(rc, 2)
        self.assertIn("more than one page", err)

    def test_a_missing_input_is_2(self):
        with tempfile.TemporaryDirectory() as folder:
            os.makedirs(os.path.join(folder, ".github", "workflows"))
            err = io.StringIO()
            self.assertEqual(oa.main([folder], fetch=Fake(), out=io.StringIO(), err=err), 2)
            self.assertIn("cannot read", err.getvalue())

    def test_usage_error_is_2(self):
        err = io.StringIO()
